#!/usr/bin/env bash
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
log="$(mktemp)"
trap 'rm -f "$log"' EXIT

bash "$here/run.sh" \
  Blaster/Smt/FFI/c/z3_shim_context.c \
  Blaster/Smt/FFI/c/z3_shim_solver.c \
  Blaster/Smt/FFI/c/z3_shim_sorts.c \
  Blaster/Smt/FFI/c/z3_shim_terms.c \
  Blaster/Smt/FFI/c/z3_shim_datatypes.c > "$log" 2>&1

bash "$here/run.sh" -eva -main main -eva-precision 3 \
  verification/frama-c/collect_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +16 valid +0 unknown +0 invalid +16 total' "$log" ||
   ! grep -Eq 'Preconditions +29 valid +0 unknown +0 invalid +29 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'AST collector (array lengths 0..3):'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

for fail_at in 0 1 2 3 4 5; do
  bash "$here/run.sh" -cpp-extra-args="-DLZ3_FAIL_AT=$fail_at" \
    -eva -main main -eva-precision 4 -eva-mlevel 20 \
    -eva-no-alloc-returns-null \
    verification/frama-c/term_quantifier_harness.c > "$log" 2>&1
  if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
     ! grep -Eq 'Assertions +[0-9]+ valid +0 unknown +0 invalid' "$log" ||
     ! grep -Eq 'Preconditions +[0-9]+ valid +0 unknown +0 invalid' "$log"; then
    cat "$log"
    exit 1
  fi
done
echo 'Quantifier allocations (success and each of five injected failures):'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -eva -main main -eva-precision 3 \
  -eva-partition-value returned_error -eva-interprocedural-splits \
  verification/frama-c/solver_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +9 valid +0 unknown +0 invalid +9 total' "$log" ||
   ! grep -Eq 'Preconditions +3 valid +0 unknown +0 invalid +3 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Solver construction and finalization:'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -eva -main main -eva-precision 3 \
  -eva-partition-value returned_error -eva-interprocedural-splits \
  verification/frama-c/solver_assuming_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +18 valid +0 unknown +0 invalid +18 total' "$log" ||
   ! grep -Eq 'Preconditions +7 valid +0 unknown +0 invalid +7 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Solver assumptions (lengths 0, 1, 3 and overflow):'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -eva -main main -eva-precision 3 \
  verification/frama-c/datatype_shape_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +7 valid +0 unknown +0 invalid +7 total' "$log" ||
   ! grep -Eq 'Preconditions +51 valid +0 unknown +0 invalid +51 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Datatype array shapes and recursive references:'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -eva -main main -eva-precision 4 \
  -eva-partition-value returned_error,constructors_created \
  -eva-interprocedural-splits \
  verification/frama-c/datatype_lifecycle_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +13 valid +0 unknown +0 invalid +13 total' "$log" ||
   ! grep -Eq 'Preconditions +67 valid +0 unknown +0 invalid +67 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Single datatype C allocations and Z3 constructor lifetime:'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -cpp-extra-args=-DLZ3_TEST_RECURSIVE \
  -eva -main main -eva-precision 4 \
  -eva-partition-value returned_error,constructors_created \
  -eva-interprocedural-splits \
  verification/frama-c/datatype_lifecycle_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +14 valid +0 unknown +0 invalid +14 total' "$log" ||
   ! grep -Eq 'Preconditions +77 valid +0 unknown +0 invalid +77 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Recursive datatype C allocations and Z3 constructor lifetime:'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -cpp-extra-args=-DLZ3_TEST_POLY \
  -eva -main main -eva-precision 4 \
  -eva-partition-value returned_error,constructors_created \
  -eva-interprocedural-splits \
  verification/frama-c/datatype_lifecycle_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +13 valid +0 unknown +0 invalid +13 total' "$log" ||
   ! grep -Eq 'Preconditions +74 valid +0 unknown +0 invalid +74 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Polymorphic datatype C allocations and Z3 constructor lifetime:'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -eva -main main -eva-precision 4 -eva-mlevel 20 \
  -eva-partition-value returned_error,constructors_created,lists_created \
  -eva-interprocedural-splits \
  verification/frama-c/datatype_mutual_harness.c > "$log" 2>&1

if ! grep -Eq '0 alarms generated by the analysis' "$log" ||
   ! grep -Eq 'Assertions +16 valid +0 unknown +0 invalid +16 total' "$log" ||
   ! grep -Eq 'Preconditions +142 valid +0 unknown +0 invalid +142 total' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Mutual datatype C allocations and Z3 constructor/list lifetime:'
grep -A 8 'ANALYSIS SUMMARY' "$log"
grep -A 4 'Evaluation of the logical properties' "$log"

bash "$here/run.sh" -wp -wp-rte -wp-fct lz3_count_fits \
  -wp-prover alt-ergo -wp-timeout 10 \
  Blaster/Smt/FFI/c/z3_shim_datatypes.c > "$log" 2>&1

if ! grep -Eq 'Proved goals: +8 / 8' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Datatype numeric count contract (WP/Alt-Ergo):'
grep -A 4 'Proved goals:' "$log"

bash "$here/run.sh" -wp -wp-rte -wp-fct lz3_alloc \
  -wp-prover alt-ergo -wp-timeout 10 \
  Blaster/Smt/FFI/c/z3_shim_datatypes.c > "$log" 2>&1

if ! grep -Eq 'Proved goals: +3 / 3' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Datatype allocation size arithmetic (WP/Alt-Ergo):'
grep -A 4 'Proved goals:' "$log"

bash "$here/run.sh" -wp -wp-rte -wp-fct lz3_term_alloc \
  -wp-prover alt-ergo -wp-timeout 10 \
  Blaster/Smt/FFI/c/z3_shim_terms.c > "$log" 2>&1

if ! grep -Eq 'Proved goals: +3 / 3' "$log"; then
  cat "$log"
  exit 1
fi
echo 'Term allocation size arithmetic (WP/Alt-Ergo):'
grep -A 4 'Proved goals:' "$log"
